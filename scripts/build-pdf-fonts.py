"""Build the bundled PDF fonts. Requires fonttools; runtime has no Python dependency."""
import sys, pathlib, json, base64, zlib, io, urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.laylo/pdf-tools'))
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib.instancer import instantiateVariableFont
source = ROOT / '.laylo/pdf-font-source'
source.mkdir(parents=True, exist_ok=True)
urls = {'NotoSans.ttf': 'https://raw.githubusercontent.com/google/fonts/main/ofl/notosans/NotoSans%5Bwdth,wght%5D.ttf', 'OFL.txt': 'https://raw.githubusercontent.com/google/fonts/main/ofl/notosans/OFL.txt'}
for name, url in urls.items():
    target = source / name
    if not target.exists(): urllib.request.urlretrieve(url, target)
codepoints = set(range(32, 0x300)) | set(range(0x400, 0x530)) | set(range(0x1e00, 0x1f00)) | set(range(0x2000, 0x2070)) | set(range(0x20a0, 0x20b0)) | {0x2192, 0x25a1}
fonts = []
for weight, name in [(400, 'Regular'), (700, 'Bold')]:
    font = instantiateVariableFont(TTFont(source / 'NotoSans.ttf'), {'wght': weight, 'wdth': 100}, inplace=True)
    options = subset.Options()
    options.hinting = False
    options.layout_features = []
    options.recalc_timestamp = False
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=codepoints)
    sub.subset(font)
    psname = 'LayloSans' + name
    for record in font['name'].names:
        if record.nameID in (1, 4, 6): record.string = psname.encode(record.getEncoding(), errors='replace')
    buf = io.BytesIO(); font.save(buf)
    raw = buf.getvalue(); cmap = font.getBestCmap(); upm = font['head'].unitsPerEm
    glyphs = {str(cp): [font.getGlyphID(g), round(font['hmtx'][g][0] * 1000 / upm)] for cp, g in cmap.items() if cp <= 65535}
    cidmap = bytearray((max(cmap) + 1) * 2)
    for cp, g in cmap.items():
        if cp <= 65535: cidmap[2 * cp:2 * cp + 2] = font.getGlyphID(g).to_bytes(2, 'big')
    head = font['head']
    fonts.append({'name': psname, 'data': base64.b64encode(zlib.compress(raw, 9)).decode(), 'length': len(raw), 'cidMap': base64.b64encode(zlib.compress(cidmap, 9)).decode(), 'glyphs': glyphs, 'bbox': [round(getattr(head, a) * 1000 / upm) for a in ['xMin', 'yMin', 'xMax', 'yMax']], 'ascent': round(font['hhea'].ascent * 1000 / upm), 'descent': round(font['hhea'].descent * 1000 / upm)})
(ROOT / 'src/pdf-fonts.mjs').write_text('// Generated by scripts/build-pdf-fonts.py. Noto Sans derivative; SIL OFL license in assets/NotoSans-OFL.txt.\nexport const pdfFonts = ' + json.dumps(fonts, separators=(',', ':')) + ';\n', encoding='utf-8')
(ROOT / 'assets/NotoSans-OFL.txt').write_bytes((source / 'OFL.txt').read_bytes())
print(json.dumps([{'name': f['name'], 'ttfBytes': f['length'], 'compressedBytes': len(base64.b64decode(f['data'])), 'characters': len(f['glyphs'])} for f in fonts]))
